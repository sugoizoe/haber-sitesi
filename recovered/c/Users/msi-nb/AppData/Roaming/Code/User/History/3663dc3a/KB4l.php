BPR201 Internet Tabanlı Programlama dersi final projesi yapıyorum. Basit bir haber sitesi istiyoruz. PHP ve MySQL kullanacağım, HTML + CSS + Bootstrap ile ön yüz yapacağım.

Proje özellikleri:
- Ana sayfada haberler listelensin (başlık, kısa özet, tarih, resim)
- Haber detay sayfası olsun
- Admin paneli olsun: sadece admin giriş yapabilsin (basit username: admin, password: 12345)
- Admin panelinde: haber ekleme, düzenleme, silme, listeleme (CRUD)
- Veritabanında haberler tablosu olsun (id, baslik, icerik, ozet, resim_yolu, tarih)
- Tasarım basit olsun, Bootstrap kullanalım, mobil uyumlu olsun
- Dosya yükleme ile haber resmi eklenebilsin

Adım adım yardımcı ol. Önce veritabanı yapısını ve bağlantı dosyasını oluşturmama yardım et.